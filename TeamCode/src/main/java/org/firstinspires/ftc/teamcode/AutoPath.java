
package org.firstinspires.ftc.teamcode;

import com.pedropathing.api.Paths;
import com.pedropathing.api.PoseFactory;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.follower.Follower;
import com.pedropathing.math.Pose;
import com.pedropathing.paths.Path;

import com.pedropathing.ivy.Command;
import com.pedropathing.ivy.Scheduler;

import static com.pedropathing.ivy.Scheduler.schedule;
import static com.pedropathing.ivy.groups.Groups.sequential;
import static com.pedropathing.ivy.pedro.PedroCommands.follow;

import com.qualcomm.robotcore.eventloop.opmode.Autonomous;
import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.util.ElapsedTime;

import org.firstinspires.ftc.teamcode.utilities.PedroPathing;
import org.firstinspires.ftc.teamcode.utilities.PedroForesightConfig;

@Autonomous(name = "AutoPath", group = "Autonomous")
public class AutoPath extends LinearOpMode {

    private Follower follower;

    private final PoseFactory poseFactory = PoseFactory.degrees();

    private final Pose start = poseFactory.of(56, 8, 90);
    private final Pose forward24 = poseFactory.of(56, 32, 90);

    private static final double TIMEOUT_SECONDS = 8.0;

    // Autonomous routine generated with Pedro Visualizer.
    public Command autoRoutine() {
        return sequential(
                follow(follower, forward24())
        );
    }

    @Override
    public void runOpMode() {

        Scheduler.reset();

        ForesightConfig config = PedroForesightConfig.create();

        // Conservative velocity constraints for the first run.
        config.maxVelocityConstraint.set(12.0);
        config.maxAccelerationConstraint.set(20.0);

        follower = PedroPathing.createFollower(
                hardwareMap,
                config
        );

        follower.holdEnd.set(false);
        follower.setPose(start);
        follower.update();

        telemetry.addData("Status", "Ready");
        telemetry.addData("Path", "Forward24");
        telemetry.update();

        try {

            waitForStart();

            if (isStopRequested()) {
                return;
            }

            ElapsedTime timer = new ElapsedTime();
            Command routine = autoRoutine();

            schedule(routine);

            while (opModeIsActive()
                    && timer.seconds() < TIMEOUT_SECONDS
                    && !gamepad1.b) {

                follower.update();
                Scheduler.execute();

                telemetry.addData("x", follower.pose().x());
                telemetry.addData("y", follower.pose().y());

                telemetry.addData(
                        "heading (deg)",
                        Math.toDegrees(follower.pose().heading())
                );

                if (follower.currentPath() != null) {

                    telemetry.addData(
                            "Distance remaining",
                            follower.distanceToEndpoint()
                    );

                    telemetry.addData(
                            "Path number",
                            follower.pathIndex()
                    );
                }

                telemetry.addData("Time", timer.seconds());
                telemetry.update();

                if (!routine.isScheduled()) {
                    break;
                }

                idle();
            }

        } finally {

            try {
                Scheduler.reset();
            } finally {
                follower.stop();
                follower.drivetrain.stop();
            }
        }
    }

    // Path generated by Pedro Pathing Visualizer.
    public Path forward24() {
        return Paths.line(start, forward24).constant(forward24);
    }
}
